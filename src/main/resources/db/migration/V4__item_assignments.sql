-- windband-inventory V4: przydział/zwrot z historią (analiza 3.1; B6 —
-- przydziały należą do bazy v1, bo stocktake (F5) czyta stany ASSIGNED).
-- member_id WITHOUT FK: members live in windband-manager (B1); the snapshot
-- name keeps history readable when WM renames or retires a person.
ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS assigned_member_id BIGINT;
ALTER TABLE inventory_items ADD COLUMN IF NOT EXISTS assigned_member_name VARCHAR(255);

-- Filter "przypisana osoba" (3.1 listy z filtrami) + F3 member view (v1.x).
CREATE INDEX IF NOT EXISTS idx_items_band_assignee
    ON inventory_items (band_id, assigned_member_id);

CREATE TABLE IF NOT EXISTS item_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL REFERENCES inventory_items (id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL,
    member_name VARCHAR(255) NOT NULL,
    assigned_at TIMESTAMP NOT NULL,
    assign_note TEXT,
    returned_at TIMESTAMP,
    returned_state VARCHAR(32),
    return_note TEXT
);

CREATE INDEX IF NOT EXISTS idx_assignments_band_item
    ON item_assignments (band_id, item_id);

-- At most ONE active (not returned) assignment per item.
CREATE UNIQUE INDEX IF NOT EXISTS uq_assignments_active_item
    ON item_assignments (item_id)
    WHERE returned_at IS NULL;
