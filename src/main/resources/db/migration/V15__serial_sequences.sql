-- Automatyczne kody pozycji (roadmapa 2026-10-20, zad. 2): licznik na
-- (zespół, typ) — program nadaje kod przy tworzeniu pozycji (np. INS-0042);
-- użytkownik nigdy go nie wpisuje i nie edytuje. Unikalność finalnego numeru
-- (band, serial_number) pilnuje istniejący częściowy indeks inventory_items.
CREATE TABLE serial_sequences (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id     BIGINT      NOT NULL,
    item_type   VARCHAR(32) NOT NULL,
    last_value  INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT uq_serial_seq_band_type UNIQUE (band_id, item_type)
);
