-- windband-inventory V2: dynamic attribute definitions (D1 attribute engine).
-- Definitions are scoped per band and per item type; "active" supports
-- deactivation instead of hard delete once values reference a definition.
CREATE TABLE IF NOT EXISTS item_attribute_defs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id BIGINT NOT NULL,
    item_type VARCHAR(32) NOT NULL,
    name VARCHAR(255) NOT NULL,
    data_type VARCHAR(16) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    display_in_list BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    options TEXT
);

CREATE INDEX IF NOT EXISTS idx_attr_defs_band_type
    ON item_attribute_defs (band_id, item_type, active);

-- Case-insensitive name uniqueness per (band, type) — enforced in the repo
-- layer as well; active-only is a business rule, so the index is partial.
CREATE UNIQUE INDEX IF NOT EXISTS uq_attr_defs_band_type_name
    ON item_attribute_defs (band_id, item_type, lower(name))
    WHERE active;
