-- windband-inventory V6: moduł inwentaryzacji F5 (analiza 3.2; spec B7 =
-- WM plan 2026-10-09 F5 w całości). Model per-jednostkowy (D1): jedna linia
-- = jedna fizyczna sztuka. Linie zdjęto-pozycyjne noszą SNAPSHOT pól
-- wyświetlanych (nazwa/seryjny/przypisany) — raport spisu pozostaje czytelny
-- nawet gdy pozycja później zmieni dane (te sama filozofia co historia
-- przydziałów). band_id denormalizowany (B1: filtry bez joina).
CREATE TABLE IF NOT EXISTS stocktakes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_by_subject VARCHAR(255),
    notes TEXT,
    started_at TIMESTAMP NOT NULL,
    finished_at TIMESTAMP,
    CONSTRAINT fk_stocktakes_band CHECK (band_id > 0)
);

CREATE INDEX IF NOT EXISTS idx_stocktakes_band ON stocktakes (band_id, id DESC);

CREATE TABLE IF NOT EXISTS stocktake_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id BIGINT NOT NULL REFERENCES stocktakes (id) ON DELETE CASCADE,
    band_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL REFERENCES inventory_items (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    serial_number VARCHAR(255),
    assigned_member_name VARCHAR(255),
    expected_status VARCHAR(32),
    found_state VARCHAR(16),
    note TEXT,
    counted_by_member_id BIGINT,
    counted_by_member_name VARCHAR(255),
    counted_at TIMESTAMP,
    -- EXTRA (nadwyżka) never comes from the snapshot; expected lines always do.
    CONSTRAINT ck_lines_state_consistency CHECK (
        (expected_status IS NULL AND found_state = 'EXTRA')
        OR (expected_status IS NOT NULL AND (found_state IS NULL OR found_state <> 'EXTRA'))
    )
);

-- One physical unit per stocktake (duplicate snapshot/extra rows are data bugs).
CREATE UNIQUE INDEX IF NOT EXISTS uq_lines_stocktake_item
    ON stocktake_lines (stocktake_id, item_id);
CREATE INDEX IF NOT EXISTS idx_lines_stocktake ON stocktake_lines (stocktake_id);
