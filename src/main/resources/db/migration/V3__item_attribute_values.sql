-- windband-inventory V3: attribute values (one normalized row per item+def).
CREATE TABLE IF NOT EXISTS item_attribute_values (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES inventory_items (id) ON DELETE CASCADE,
    attribute_def_id BIGINT NOT NULL REFERENCES item_attribute_defs (id),
    value_text TEXT
);

CREATE INDEX IF NOT EXISTS idx_attr_values_item ON item_attribute_values (item_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_attr_values_item_def
    ON item_attribute_values (item_id, attribute_def_id);
