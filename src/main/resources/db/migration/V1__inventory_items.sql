-- windband-inventory V1: inventory items (decision D1/B6).
-- band_id has NO foreign key: bands live in windband-manager and are never
-- duplicated here (decision B1); authz is enforced per request via the WM API.
-- Column names avoid reserved-word pitfalls (value_text precedent from WM).
CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    item_type VARCHAR(32) NOT NULL,
    lifecycle_status VARCHAR(32) NOT NULL,
    warehouse VARCHAR(16) NOT NULL,
    serial_number VARCHAR(255),
    description TEXT,
    notes TEXT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_items_band ON inventory_items (band_id);

CREATE INDEX IF NOT EXISTS idx_items_band_type ON inventory_items (band_id, item_type);

-- Serial numbers are unique per band when present (NULLs unlimited).
CREATE UNIQUE INDEX IF NOT EXISTS uq_items_band_serial
    ON inventory_items (band_id, serial_number)
    WHERE serial_number IS NOT NULL;
