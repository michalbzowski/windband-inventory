-- windband-inventory V5: warehouse transfers (decision B6 — MAIN/SERVICE/ARCHIVE
-- plus movement history). Append-only event rows; inventory_items.warehouse is
-- the current location and is always moved together with a row here (one
-- transaction). from <> to mirrors the domain rule at DB level.
-- band_id has no FK (bands live in WM — B1); item_id does (same database).
CREATE TABLE IF NOT EXISTS warehouse_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    from_warehouse VARCHAR(16) NOT NULL,
    to_warehouse VARCHAR(16) NOT NULL,
    note TEXT,
    transferred_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_transfers_item FOREIGN KEY (item_id) REFERENCES inventory_items (id),
    CONSTRAINT ck_transfers_different_warehouses CHECK (from_warehouse <> to_warehouse)
);

CREATE INDEX IF NOT EXISTS idx_transfers_band ON warehouse_transfers (band_id);

CREATE INDEX IF NOT EXISTS idx_transfers_item ON warehouse_transfers (item_id, transferred_at DESC);
